import { createRequire } from "module"; const require = createRequire(import.meta.url); const { chromium } = require("playwright");
const out = process.argv[2] || "/home/claude/game/tmp/shots";
import fs from "fs"; fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errs.push(m.type() + ": " + m.text()); });
page.on("pageerror", (e) => errs.push("PAGEERROR: " + e.message + "\n" + e.stack));
await page.goto("http://localhost:8766/index.html");
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "/01_lobby.png" });
await page.click("text=开始冒险");
await page.waitForTimeout(1500);
await page.screenshot({ path: out + "/02_start.png" });
await page.keyboard.down("KeyD");
await page.keyboard.down("KeyJ");
await page.waitForTimeout(1500);
await page.keyboard.up("KeyD");
await page.screenshot({ path: out + "/03_fight.png" });
await page.keyboard.press("KeyK");
await page.waitForTimeout(600);
await page.screenshot({ path: out + "/04_skill.png" });
await page.waitForTimeout(3000);
await page.screenshot({ path: out + "/05_fight2.png" });
console.log(errs.slice(0, 30).join("\n"));
await browser.close();
